create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  username text not null check (username ~ '^[A-Za-z0-9_]{3,20}$'),
  created_at timestamptz not null default now()
);

create unique index if not exists profiles_username_lower_idx on public.profiles (lower(username));

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, username)
  values (
    new.id,
    coalesce(
      nullif(new.raw_user_meta_data ->> 'username', ''),
      'user_' || substr(replace(new.id::text, '-', ''), 1, 8)
    )
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create table if not exists public.trails (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(trim(title)) between 3 and 80),
  region text not null check (char_length(trim(region)) between 2 and 60),
  difficulty text not null check (difficulty in ('easy', 'moderate', 'hard')),
  distance_km numeric(5, 1) not null check (distance_km > 0 and distance_km <= 300),
  elevation_gain_m integer not null check (elevation_gain_m between 0 and 5000),
  duration_hours numeric(4, 1) not null check (duration_hours > 0 and duration_hours <= 72),
  description text not null check (char_length(trim(description)) between 20 and 2000),
  image_url text check (
    image_url is null or (image_url ~* '^(https?://|/images/)' and char_length(image_url) <= 500)
  ),
  owner_id uuid not null default auth.uid(),
  created_at timestamptz not null default now(),
  constraint trails_owner_id_fkey foreign key (owner_id)
    references public.profiles (id) on delete cascade
);

create index if not exists trails_owner_id_idx on public.trails (owner_id);
create index if not exists trails_created_at_idx on public.trails (created_at desc);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  trail_id bigint not null references public.trails (id) on delete cascade,
  body text not null check (char_length(trim(body)) between 1 and 500),
  owner_id uuid not null default auth.uid(),
  created_at timestamptz not null default now(),
  constraint comments_owner_id_fkey foreign key (owner_id)
    references public.profiles (id) on delete cascade
);

create index if not exists comments_trail_id_idx on public.comments (trail_id);
create index if not exists comments_owner_id_idx on public.comments (owner_id);

create table if not exists public.likes (
  trail_id bigint not null references public.trails (id) on delete cascade,
  owner_id uuid not null default auth.uid(),
  created_at timestamptz not null default now(),
  primary key (trail_id, owner_id),
  constraint likes_owner_id_fkey foreign key (owner_id)
    references public.profiles (id) on delete cascade
);

create index if not exists likes_owner_id_idx on public.likes (owner_id);

alter table public.profiles enable row level security;
alter table public.trails enable row level security;
alter table public.comments enable row level security;
alter table public.likes enable row level security;
